import { describe, it, expect } from 'vitest'
import { startOfWeek, weekDates, formatPeriod, addDays } from './calendarRange'

describe('addDays', () => {
  it.each([
    ['日をまたぐ', '2026-08-06', 1, '2026-08-07'],
    ['月をまたぐ', '2026-08-31', 1, '2026-09-01'],
    ['年をまたぐ', '2026-12-31', 1, '2027-01-01'],
    ['負の値で減算する', '2026-09-01', -1, '2026-08-31'],
    ['閏日をまたぐ', '2028-02-28', 2, '2028-03-01'],
    ['0 なら同じ日', '2026-08-06', 0, '2026-08-06'],
  ])('%s（%s + %i → %s）', (_label, date, days, expected) => {
    const result = addDays(date, days)

    expect(result).toBe(expected)
  })
})

describe('startOfWeek', () => {
  it.each([
    ['木曜日ならその週の日曜日', '2026-08-06', '2026-08-02'],
    ['日曜日ならその日', '2026-08-02', '2026-08-02'],
    ['土曜日なら6日前の日曜日', '2026-08-08', '2026-08-02'],
    ['月をまたぐ週でも正しい日曜日', '2026-09-01', '2026-08-30'],
  ])('%s（%s → %s）', (_label, date, expected) => {
    const result = startOfWeek(date)

    expect(result).toBe(expected)
  })
})

describe('weekDates', () => {
  it('日曜始まり土曜終わりの7日を返す', () => {
    const dates = weekDates('2026-08-06')

    expect(dates).toEqual([
      '2026-08-02', '2026-08-03', '2026-08-04', '2026-08-05',
      '2026-08-06', '2026-08-07', '2026-08-08',
    ])
  })

  it('月をまたぐ週も連続した7日を返す', () => {
    const dates = weekDates('2026-09-01')

    expect(dates).toEqual([
      '2026-08-30', '2026-08-31', '2026-09-01', '2026-09-02',
      '2026-09-03', '2026-09-04', '2026-09-05',
    ])
  })
})

describe('formatPeriod', () => {
  it.each([
    ['単一月なら「YYYY年M月」', ['2026-08-02', '2026-08-08'], '2026年8月'],
    ['月をまたぐと「YYYY年M月 – M月」', ['2026-08-30', '2026-09-05'], '2026年8月 – 9月'],
    ['年をまたぐと両方の年を出す', ['2026-12-27', '2027-01-02'], '2026年12月 – 2027年1月'],
    ['同じ月で年だけ違っても年をまたぐ扱い', ['2026-08-01', '2027-08-01'], '2026年8月 – 2027年8月'],
    ['1日だけでも単一月として扱う', ['2026-08-06'], '2026年8月'],
    ['空配列は空文字', [], ''],
  ])('%s', (_label, dates, expected) => {
    const label = formatPeriod(dates)

    expect(label).toBe(expected)
  })
})
